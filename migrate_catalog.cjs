// Migration script to cleanly reorganize Movies, Series, and Live TV
const fs = require("fs");
const path = require("path");

const dbPath = path.join(__dirname, "data", "database.json");
const initPath = path.join(__dirname, "data", "initial_data.json");

const db = JSON.parse(fs.readFileSync(dbPath, "utf8"));

// 1. Move all foreign/linear TV channels currently in Movies to Live TV
let movedMovieChannels = 0;
let movedSeriesChannels = 0;

db.user_streams.forEach((s) => {
  if (s.category === "Movies") {
    const isChannel = !s.id.startsWith("tr-film-");
    if (isChannel) {
      s.category = "Live TV";
      s.sub_category = "Sinema Kanalları";
      s.channel_group = "Sinema Kanalları";
      s.tags = Array.from(new Set([...(s.tags || []), "sinema kanalı", "live tv", "canlı tv"]));
      movedMovieChannels++;
    }
  } else if (s.category === "Series") {
    const isChannel = !s.id.startsWith("tr-dizi-");
    if (isChannel) {
      s.category = "Live TV";
      s.sub_category = "Dizi Kanalları";
      s.channel_group = "Dizi Kanalları";
      s.tags = Array.from(new Set([...(s.tags || []), "dizi kanalı", "live tv", "canlı tv"]));
      movedSeriesChannels++;
    }
  }
});

console.log(`Reclassified ${movedMovieChannels} movie TV channels into Live TV (Sinema Kanalları)`);
console.log(`Reclassified ${movedSeriesChannels} series TV channels into Live TV (Dizi Kanalları)`);

